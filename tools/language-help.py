"""language-help.py — language/help.txt, read by (help name), from the doc comments of the language:

    // (name args) description                      in src/lang/*.h
    ; (name args) description                       in language/*.moritz

A line may name several forms that share the description; continuation lines start with the same
comment marker and an indent. Only forms naming something the file registers or defines count.
Run it after editing the language:  python3 tools/language-help.py   (the result is committed)
"""
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
LIBS = [["src/lang/core.h"], ["src/lang/std.h", "language/std.moritz"], ["src/lang/system.h", "language/system.moritz"],
        ["src/lang/scientific.h", "language/scientific.moritz"], ["src/lang/signals.h", "language/signals.moritz"],
        ["src/lang/music.h", "src/lang/music/midi.h", "language/music.moritz"], ["language/plot.moritz"],
        ["src/langpatch.cpp", "src/session.cpp"]]
FORM = re.compile(r"^\(([^\s()]+)[^)]*\)")
REG = re.compile(r'(?:[iI]\.def\(|[iI]\.def_form\(|\ba\(|\{)\s*"([^"]+)"')
DEF = re.compile(r"^function\s+([^\s()]+)", re.M)


def entries(path):
    text_all = path.read_text()
    code = path.suffix == ".moritz"
    marker = ";" if code else "//"
    known = set(DEF.findall(text_all)) if code else set(REG.findall(text_all))
    out, block = [], None
    for raw in text_all.splitlines():
        line = raw.strip()
        if not line.startswith(marker):
            if block: out.append(block); block = None
            continue
        text = line[len(marker):].strip()
        after = raw.lstrip()[len(marker):]
        if block and (after.startswith("  ") or after.startswith("\t")):
            block[2].append(text)
        elif text.startswith("("):
            if block: out.append(block)
            names, sig, rest = [], [], text
            while True:
                m = FORM.match(rest)
                if not m or m.group(1) not in known: break
                names.append(m.group(1)); sig.append(rest[:m.end()]); rest = rest[m.end():].strip()
            desc = rest.lstrip(":").strip()
            block = (names, "  ".join(sig), [desc] if desc else [])
        else:
            if block: out.append(block); block = None
    if block: out.append(block)
    return [(n, s, d) for n, s, d in out if n]


lines = []
for files in LIBS:
    for f in files:
        for names, sig, desc in entries(ROOT / f):
            lines.append("#" + " ".join(names))
            lines.append("  " + sig)
            lines.extend("  " + d for d in desc)
(ROOT / "language/help.txt").write_text(
    "# help.txt — generated by tools/language-help.py from the doc comments of the language; do not edit\n"
    + "\n".join(lines) + "\n")
print(f"language/help.txt: {sum(1 for l in lines if l.startswith('#'))} entries")
