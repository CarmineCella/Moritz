"""musil-help.py — help/musil/help.txt, read by (help name) and by the code editor, from the doc comments of
Musil as Moritz uses it:

    // (name args) description                      in musil/src/*.h, and src/session.cpp (Moritz from Musil)
    ; (name args) description                       in musil/src/*.mu

A line may name several forms that share the description; continuation lines start with the same
comment marker and an indent. Only forms naming something the file registers or defines count.
Musil's own help.txt (musil/tools/gendoc.py, for Musil on its own) also documents the live, plot and
controls libraries, which Moritz leaves out (Moritz plays and draws); this one documents what Moritz has.
Run it after editing:  python3 tools/musil-help.py   (the result is committed)
"""
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
M = "musil/src/"
LIBS = [[M + "core.h"], [M + "std.h", M + "std.mu"], [M + "system.h", M + "system.mu"],
        [M + "scientific.h", M + "scientific.mu"], [M + "signals.h", M + "signals.mu"],
        [M + "music.h", M + "music/midi.h", M + "music.mu"], [M + "live.mu"], ["src/musil_host.h", "src/session.cpp"]]
FORM = re.compile(r"^\(([^\s()]+)[^)]*\)")
REG = re.compile(r'(?:[iI]\.def\(|\ba\(|\{)\s*"([^"]+)"')
DEF = re.compile(r"^function\s+([^\s()]+)", re.M)


def entries(path):
    text_all = path.read_text()
    code = path.suffix == ".mu"
    marker = ";" if code else "//"
    known = set(DEF.findall(text_all)) if code else set(REG.findall(text_all))
    out, block = [], None
    for raw in text_all.splitlines():
        line = raw.strip()
        if not line.startswith(marker):
            if block: out.append(block); block = None
            continue
        text = line[len(marker):].strip()
        after = raw.lstrip()[len(marker):]
        if block and (after.startswith("  ") or after.startswith("\t")):
            block[2].append(text)
        elif text.startswith("("):
            if block: out.append(block)
            names, sig, rest = [], [], text
            while True:
                m = FORM.match(rest)
                if not m or m.group(1) not in known: break
                names.append(m.group(1)); sig.append(rest[:m.end()]); rest = rest[m.end():].strip()
            desc = rest.lstrip(":").strip()
            block = (names, "  ".join(sig), [desc] if desc else [])
        else:
            if block: out.append(block); block = None
    if block: out.append(block)
    return [(n, s, d) for n, s, d in out if n]


lines = []
for files in LIBS:
    for f in files:
        for names, sig, desc in entries(ROOT / f):
            lines.append("#" + " ".join(names))
            lines.append("  " + sig)
            lines.extend("  " + d for d in desc)
(ROOT / "help/musil/help.txt").write_text(
    "# help.txt — generated by tools/musil-help.py from the doc comments of Musil as Moritz uses it; do not edit\n"
    + "\n".join(lines) + "\n")
print(f"help/musil/help.txt: {sum(1 for l in lines if l.startswith('#'))} entries")
